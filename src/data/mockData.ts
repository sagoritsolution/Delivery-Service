export function calculateDeliveryFeeFromDistance(
  distanceKm: number,
  config: DeliveryConfig = INITIAL_DELIVERY_CONFIG
): { fee: number; formulaExplanation: string } {
  const d = Math.max(0.5, distanceKm);
  const extraKm = Math.max(0, d - config.includedDistanceKm);
  const calculated = config.baseFee + Math.round(extraKm * config.extraRatePerKm);
  const finalFee = Math.max(config.minDeliveryFee, calculated) + config.peakHourSurcharge;

  const formulaExplanation = `${config.baseFee}৳ (প্রথম ${config.includedDistanceKm} কি.মি.) + (${extraKm.toFixed(1)} কি.মি. × ${config.extraRatePerKm}৳/কি.মি.) = ${finalFee}৳`;
  return { fee: finalFee, formulaExplanation };
}

